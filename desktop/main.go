package main

import (
	"embed"
	"io/fs"
	"os"
	"fmt"
	"errors"
	"time"
	"log"
	"strings"
	"encoding/json"

	"github.com/wailsapp/wails/v3/pkg/application"
)

//go:embed ui/*
var embeddedUI embed.FS

// A confirmation is successful only when the executor supplies a parsed,
// explicit VERIFIED receipt; an arbitrary JSON string is not sufficient.
func isVerifiedHeadlessReceipt(output string) bool {
	var receipt struct { Status string `json:"status"` }
	return json.Unmarshal([]byte(output), &receipt) == nil && receipt.Status == "VERIFIED"
}

func headlessReceiptHasStatus(output, expected string) bool {
	var receipt struct { Status string `json:"status"` }
	return json.Unmarshal([]byte(output), &receipt) == nil && receipt.Status == expected
}

// The OS accepting a process start request is a distinct state from an
// optional app missing or a verified GUI session.
func headlessLaunchReceipt(result string, err error) (string, error) {
	if err != nil { return "", err }
	var receipt struct { Status string `json:"status"` }
	if json.Unmarshal([]byte(result), &receipt) != nil || receipt.Status != "LAUNCH_REQUESTED" {
		return "", errors.New("external application was not launched")
	}
	return result, nil
}

// Headless verbs are intentionally finite. Mutation only occurs with a digest
// generated by a separate preview; never accept an arbitrary binary, path or
// command from a CLI argument. Useful for fresh HOME smoke without a GUI.
func headless(args []string) (string, error) {
	if len(args) != 1 {
		return "", errors.New("provide exactly one supported flag; use --help")
	}
	service := &DesktopService{}
	switch args[0] {
	case "--doctor":
		return runEmbeddedPython(25*time.Second, "gpupanel-workstation.py", "doctor")
	case "--versions":
		return runEmbeddedPython(25*time.Second, "gpupanel-workstation.py", "versions")
	case "--launcher-plan":
		return service.LauncherPlan()
	case "--uv-tool-plan":
		return service.UvToolPlan()
	case "--uv-tool-status":
		return service.UvToolStatus()
	case "--uv-project-plan":
		return service.UvProjectPlan()
	case "--uv-project-status":
		return service.UvProjectStatus()
	case "--help":
		return "GPUPanel Desktop: GUI | --doctor | --versions | --launcher-plan | --launcher-install=SHA256 | --uv-tool-plan | --uv-tool-status | --uv-tool-install=SHA256 | --uv-project-plan | --uv-project-status | --uv-project-create=SHA256 | --open-project-terminal=NAME | --open-project-editor=NAME | --source-plan=NAME | --source-export=NAME:SHA256 | --source-inspect=FILE | --source-restore=FILE:SHA256\n", nil
	default:
		// Source transfer CLI uses the exact Wails service methods and the same
		// plan/ZIP digests. No free-form filesystem paths or commands.
		if strings.HasPrefix(args[0], "--source-plan=") {
			name := strings.TrimPrefix(args[0], "--source-plan=")
			return service.SourcePlan(name)
		}
		if strings.HasPrefix(args[0], "--source-export=") {
			pieces := strings.SplitN(strings.TrimPrefix(args[0], "--source-export="), ":", 2)
			if len(pieces) != 2 || !projectPattern.MatchString(pieces[0]) ||
				!digestPattern.MatchString(pieces[1]) {
				return "", errors.New("invalid source export approval")
			}
			value, err := service.SourceExport(pieces[0], pieces[1])
			if err != nil { return "", err }
			if !headlessReceiptHasStatus(value, "EXPORTED") {
				return "", errors.New("source export did not succeed")
			}
			return value, nil
		}
		if strings.HasPrefix(args[0], "--source-inspect=") {
			filename := strings.TrimPrefix(args[0], "--source-inspect=")
			return service.SourceInspect(filename)
		}
		if strings.HasPrefix(args[0], "--source-restore=") {
			pieces := strings.SplitN(strings.TrimPrefix(args[0], "--source-restore="), ":", 2)
			if len(pieces) != 2 || !sourceBundlePattern.MatchString(pieces[0]) ||
				!digestPattern.MatchString(pieces[1]) {
				return "", errors.New("invalid source restore approval")
			}
			value, err := service.SourceRestore(pieces[0], pieces[1])
			if err != nil { return "", err }
			if !isVerifiedHeadlessReceipt(value) {
				return "", errors.New("source restore was not independently verified")
			}
			return value, nil
		}
		// Headless launch actions exist for bounded real-process acceptance
		// with stub binaries. They call the identical service methods used
		// by Wails; the result is LAUNCH_REQUESTED, never a GUI success claim.
		if strings.HasPrefix(args[0], "--open-project-terminal=") {
			project := strings.TrimPrefix(args[0], "--open-project-terminal=")
			if !projectPattern.MatchString(project) {
				return "", errors.New("invalid local project name")
			}
			return headlessLaunchReceipt(service.OpenProjectTerminal(project))
		}
		if strings.HasPrefix(args[0], "--open-project-editor=") {
			project := strings.TrimPrefix(args[0], "--open-project-editor=")
			if !projectPattern.MatchString(project) {
				return "", errors.New("invalid local project name")
			}
			return headlessLaunchReceipt(service.OpenProjectEditor(project))
		}
		if strings.HasPrefix(args[0], "--launcher-install=") {
			digest := strings.TrimPrefix(args[0], "--launcher-install=")
			if !digestPattern.MatchString(digest) {
				return "", errors.New("invalid desktop launcher approval")
			}
			return service.LauncherInstall(digest)
		}
		if strings.HasPrefix(args[0], "--uv-tool-install=") {
			digest := strings.TrimPrefix(args[0], "--uv-tool-install=")
			if !digestPattern.MatchString(digest) {
				return "", errors.New("invalid tool approval SHA-256")
			}
			result, err := service.UvToolInstall(digest)
			if err != nil { return "", err }
			if !isVerifiedHeadlessReceipt(result) {
				return "", errors.New("uv tool install was not independently verified")
			}
			return result, nil
		}
		if strings.HasPrefix(args[0], "--uv-project-create=") {
			digest := strings.TrimPrefix(args[0], "--uv-project-create=")
			if !digestPattern.MatchString(digest) {
				return "", errors.New("invalid project approval SHA-256")
			}
			result, err := service.UvProjectCreate(digest)
			if err != nil { return "", err }
			if !isVerifiedHeadlessReceipt(result) {
				return "", errors.New("uv project creation was not independently verified")
			}
			return result, nil
		}
		return "", errors.New("unsupported command; no arbitrary shell or privileged operation")
	}
}
func main() {
	if len(os.Args) > 1 {
		output, err := headless(os.Args[1:])
		if err != nil { log.Fatal(err) }
		fmt.Print(output)
		return
	}
	ui, err := fs.Sub(embeddedUI, "ui")
	if err != nil {
		log.Fatal(err)
	}
	app := application.New(application.Options{
		Name: "GPUPanel Workstation",
		Assets: application.AssetOptions{Handler: application.AssetFileServerFS(ui)},
		Services: []application.Service{application.NewService(&DesktopService{})},
	})
	window := app.Window.NewWithOptions(application.WebviewWindowOptions{
		Name: "workstation", Title: "GPUPanel · Local Workstation",
		Width: 1050, Height: 730, MinWidth: 800, MinHeight: 560,
		BackgroundColour: application.NewRGB(247, 248, 250),
	})
	window.Center()
	window.Show()
	if err := app.Run(); err != nil {
		log.Fatal(err)
	}
}
